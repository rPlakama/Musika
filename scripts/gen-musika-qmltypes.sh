# Generate the lint-only QML type information for the runtime-registered
# `musika` module (qtbridge). qmllint/qmlls cannot see types registered from
# Rust at engine startup, so without this file every `Palette.*`/`Backend.*`
# access is a blind spot (and the check script has to filter the noise).
#
#   scripts/gen-musika-qmltypes.sh
#
# Palette is generated from the `qproperty!` roles in `src/palette.rs`; Backend
# is declared as a QObject-based singleton without members (its surface is too
# large to mirror, and its dynamic accesses stay filtered in check-qml.sh).
# The generated files are tooling-only: they are not embedded in the app and
# never reach the runtime engine.
set -eu

cd "$(dirname "$0")/.."

out=scripts/lint/musika
mkdir -p "$out"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The qproperty! macros are multi-line; join them and keep role name + notify.
tr '\n' ' ' < src/palette.rs \
    | grep -oE 'qproperty!\( *"[^"]+", *Member *= *[a-z_]+, *Notify *= *[a-z_]+ *\)' \
    | sed -E 's/^qproperty!\( *"([^"]+)", *Member *= *[a-z_]+, *Notify *= *([a-z_]+) *\)$/\1 \2/' \
    > "$tmp/roles"

if [ ! -s "$tmp/roles" ]; then
    echo "gen-musika-qmltypes: no qproperty roles found in src/palette.rs" >&2
    exit 1
fi

awk '{ printf "        Property { name: \"%s\"; type: \"QColor\"; read: \"%s\"; notify: \"%s\"; index: %d }\n", $1, $1, $2, NR - 1 }' \
    "$tmp/roles" > "$tmp/props"
awk '{ printf "        Signal { name: \"%s\" }\n", $2 }' "$tmp/roles" > "$tmp/signals"

{
    cat <<'EOF'
import QtQuick.tooling 1.2

// Tooling-only QML type information for the runtime-registered `musika` module
// (qtbridge). GENERATED by scripts/gen-musika-qmltypes.sh from src/palette.rs.
// Do not edit by hand; re-run the script after changing the Palette roles.
//
// Palette is fully declared so qmllint catches a misspelled colour role.
// Backend is declared as a QObject-based singleton without members: that
// removes the false "unqualified access" noise for the module while its large
// slot/property surface stays lint-blind (filtered in scripts/check-qml.sh).
Module {
    Component {
        name: "QQuickPalette"
        accessSemantics: "reference"
        prototype: "QObject"
        exports: ["musika/Palette 1.0"]
        isSingleton: true
EOF
    cat "$tmp/props"
    cat "$tmp/signals"
    cat <<'EOF'
        Method { name: "apply"; Parameter { name: "payload"; type: "QString" } }
        Method { name: "reset" }
    }
    Component {
        name: "QQuickBackend"
        accessSemantics: "reference"
        prototype: "QObject"
        exports: ["musika/Backend 1.0"]
        isSingleton: true
    }
}
EOF
} > "$out/plugins.qmltypes"

cat > "$out/qmldir" <<'EOF'
module musika
typeinfo plugins.qmltypes
depends QtQuick
EOF

echo "gen-musika-qmltypes: wrote $out/qmldir and $out/plugins.qmltypes ($(wc -l < "$out/plugins.qmltypes") lines)"
