//! Dynamic Material You palette singleton (THM-4).
//!
//! QML reads `Palette.primary`, `Palette.surfaceContainerHigh`, … (registered
//! from Rust like `Backend`, so notifications work). The defaults mirror the
//! static MY3 palette in `Theme.js`; `apply()` re-seeds the tonal family from
//! the cover scheme generated by `colors.rs` (DB6, matugen engine).
//!
//! Semantic and structural tokens do NOT live here: shape, motion, type,
//! z-ladder and the pre-mixed state layers stay in `Theme.js`.

