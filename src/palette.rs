/// Assigns one role if present and notifies only when it actually changed.
macro_rules! apply_role {
    ($self:ident, $roles:ident, $field:ident, $key:literal, $signal:ident) => {
        if let Some(value) = $roles.get($key) {
            if $self.$field != *value {
                $self.$field = value.clone();
                $self.$signal();
            }
        }
    };
}

